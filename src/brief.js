'use strict';
// A decision brief as Markdown: what the agents concluded, what you hold, and what you did.
// Everything here is copied from the run. Nothing is added or inferred.

const fmt = (n, d = 2) => (typeof n === 'number' && Number.isFinite(n) ? n.toLocaleString('en-US', { minimumFractionDigits: d, maximumFractionDigits: d }) : 'data to be confirmed');

function positionLine(position, price) {
  if (!position) return 'No position recorded in TradeDesk for this ticker.';
  const bits = [`${Math.round(position.quantity * 1e6) / 1e6} units`];
  if (position.averagePrice != null) bits.push(`average cost ${fmt(position.averagePrice)}`);
  if (position.averagePrice != null && price && price.close) {
    const pct = (price.close / position.averagePrice - 1) * 100;
    bits.push(`last close ${fmt(price.close)} (${pct >= 0 ? '+' : ''}${pct.toFixed(1)}% vs cost)`);
  }
  return bits.join(', ');
}

function section(title, body) {
  const t = String(body || '').trim();
  return t ? `\n## ${title}\n\n${t}\n` : '';
}

function buildBrief({ entry, result, position }) {
  const s = (result && result.sections) || {};
  const m = (result && result.model) || (entry && entry.model) || {};
  const lines = [];
  lines.push(`# ${entry.ticker} decision brief`);
  lines.push('');
  lines.push(`**Rating: ${entry.rating}**  `);
  lines.push(`Analysis date: ${entry.date}  `);
  lines.push(`Model: ${m.provider || 'data to be confirmed'} / quick ${m.quick || '?'} / deep ${m.deep || '?'}, debate rounds ${m.debate_rounds ?? '?'}  `);
  if (entry.priceAtAnalysis) lines.push(`Close on ${entry.priceAtAnalysis.date}: ${fmt(entry.priceAtAnalysis.close)}  `);
  lines.push(`Your position: ${positionLine(position, entry.priceAtAnalysis)}`);
  lines.push('');
  lines.push('> Research aid generated by language models. It is not financial advice, can be wrong, and places no orders. Check the facts before acting.');
  lines.push(section('Portfolio manager decision', s.decision));
  lines.push(section('Trader proposal', s.trader_plan));
  lines.push(section('Research manager plan', s.research_plan));
  lines.push(section('Bull case', s.bull));
  lines.push(section('Bear case', s.bear));
  lines.push(section('Risk team: aggressive', s.risk_aggressive));
  lines.push(section('Risk team: conservative', s.risk_conservative));
  lines.push(section('Risk team: neutral', s.risk_neutral));
  lines.push(section('Market analyst', s.market));
  lines.push(section('Sentiment analyst', s.sentiment));
  lines.push(section('News analyst', s.news));
  lines.push(section('Fundamentals analyst', s.fundamentals));
  if (s.memory_note) lines.push(section('Notes from the run', s.memory_note));
  if (entry.action) {
    const a = entry.action;
    lines.push(section('What you did', `${a.type}${a.quantity != null ? `, ${a.quantity} units` : ''}${a.price != null ? ` at ${fmt(a.price)}` : ''}${a.note ? `\n\n${a.note}` : ''}\n\nRecorded ${a.at}`));
  }
  return lines.filter((l) => l !== undefined).join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

module.exports = { buildBrief, positionLine };
